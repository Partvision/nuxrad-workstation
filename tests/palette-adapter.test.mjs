import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const initial = { customColorTables: {'BR:Mine':'user table'}, colorTableOverrides:{BR:'custom:BR:Mine',BV:'bundled-original',ZDR:'untouched'},syncWithAccount:true };
const settings = structuredClone(initial), data = new Map();
let calls = 0;
const stores = new Map([['settings',{settings,$patch:fn=>fn()}],['radar',{refreshColorTable:async()=>{calls++;}}]]);
const context = {document:{querySelector:()=>({__vue_app__:{config:{globalProperties:{$pinia:{_s:stores}}}}})},localStorage:{getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v)}};
vm.createContext(context);
vm.runInContext(await fs.readFile(new URL('../palette-adapter.js',import.meta.url),'utf8'),context);
const api = context.NuxradThemePalettes.create();
assert.equal(api.install().available,true);
await api.apply();
assert.equal(calls,0);
assert.deepEqual(JSON.parse(JSON.stringify(settings)),initial);
await api.apply({reflectivity:'classic',velocity:'color-friendly'});
assert.equal(calls,1);
assert.equal(settings.colorTableOverrides.ZDR,'untouched');
assert.match(settings.colorTableOverrides.BR,/^custom:BR:NUXRAD Themes/);
const first=JSON.stringify(settings);
await api.apply({reflectivity:'classic',velocity:'color-friendly'});
assert.equal(JSON.stringify(settings),first);
assert.match(api.export('classic','velocity'),/Units: m\/s\nScale: 1/);
assert.match(api.export('classic','reflectivity'),/Product: BR\nUnits: dBZ/);
await api.apply({reflectivity:'contrast'});
assert.equal(Object.keys(settings.customColorTables).length,3);
const reloaded = context.NuxradThemePalettes.create();
assert.equal(reloaded.getStatus().slots.reflectivity.owned,true);
await reloaded.restore();
assert.deepEqual(JSON.parse(JSON.stringify(settings)),initial);
await api.apply({reflectivity:'classic',velocity:'contrast'});
settings.colorTableOverrides.BR='external-edit';
const bvKey=settings.colorTableOverrides.BV.slice(7);
settings.customColorTables[bvKey]='external table edit';
await api.restore();
assert.equal(settings.colorTableOverrides.BR,'external-edit');
assert.equal(settings.colorTableOverrides.BV,initial.colorTableOverrides.BV);
assert.equal(settings.customColorTables[bvKey],'external table edit');
assert.equal(settings.customColorTables['BR:Mine'],'user table');
console.log('PASS: keep, apply, idempotence, product isolation, export, persisted restore, external edit preservation');

